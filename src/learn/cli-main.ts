/** `--name value`, `--name=value`, or undefined when absent. A bare `--name` yields ''. */
function optionValue(argv: string[], name: string): string | undefined {
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === `--${name}`) {
      const next = argv[i + 1];
      if (next === undefined || next.startsWith('--')) return '';
      return next;
    }
    if (arg.startsWith(`--${name}=`)) return arg.slice(name.length + 3);
  }
  return undefined;
}

function optionNumber(argv: string[], name: string): number | undefined {
  const raw = optionValue(argv, name);
  if (raw === undefined || raw === '') return undefined;
  const parsed = Number(raw);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : undefined;
}

function hasFlag(argv: string[], name: string): boolean {
  return argv.includes(`--${name}`);
}

/** Open the three handles a command needs. Closed, store first, in `finally`. */
async function openDbs(): Promise<LearnDbs> {
  const { openKnowledgeStore } = await import('./knowledge-store.js');
  const { openLearningDb } = await import('./learning-store.js');
  const { initDatabase } = await import('../db.js');
  return { store: openKnowledgeStore(), learning: openLearningDb(), index: initDatabase() };
}

function closeDbs(dbs: LearnDbs): void {
  // The store first: its context holds the whole in-memory graph.
  try {
    dbs.store.close();
  } catch {
    // best effort
  }
  for (const db of [dbs.learning, dbs.index]) {
    try {
      db.close();
    } catch {
      // best effort
    }
  }
}

/**
 * The subprocess count a baseline needs: the signal tasks of the train split.
 *
 * `solve` spends one call per task.
 * Bootstrap solves the same set twice, once with an empty snapshot and once with the candidates.
 * The bootstrap multiplier is therefore 2.
 */
export function baselineCallCount(db: Database.Database, times = 1): number {
  return listTasks(db, { split: 'train', kinds: SIGNAL_KINDS, tiers: SIGNAL_TIERS }).length * times;
}

/**
 * The run a solve should record against.
 *
 * Tasks generated by `learn tasks` belong to a run that command already
 * finished.
 * A still-running run that owns every task in this batch is the run being continued.
 * A solve that stops for budget must mark that same run `stopped` and keep its attempts.
 * Otherwise this solve starts its own.
 */
function runIdForSolve(
  db: LearnDbs['learning'],
  tasks: LearningTask[],
  budget: { maxCalls: number; maxUsd: number; split: string }
): string {
  const owners = [...new Set(tasks.map(task => task.runId))];
  if (owners.length === 1) {
    const existing = getRun(db, owners[0]);
    if (existing?.status === 'running') return existing.id;
  }
  return createRun(db, { phase: 'improve', seed: 1, budget });
}

/** A refusal message when the baseline cannot be afforded, or null. */
export function baselineRefusal(count: number, maxCalls: number): string | null {
  if (count <= maxCalls) return null;
  return (
    `baseline needs ${count} subprocess calls, above EPISODIC_MEMORY_LEARN_MAX_CALLS=${maxCalls}; ` +
    'refusing to start a run that cannot afford its own measurement'
  );
}

/** Run `fn` under the learn lock, turning a held lock into exit code 1. */
async function underLock(
  deps: LearnCliDeps,
  fn: (pids: PidRegistry) => Promise<number>
): Promise<number> {
  try {
    return await withLearnLock(fn);
  } catch (error) {
    if (error instanceof LearnLockHeld) {
      deps.stderr(`episodic-memory learn: ${error.message}\n`);
      return 1;
    }
    throw error;
  }
}

async function commandTasks(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const config = learnConfig();
  const seed = optionNumber(argv, 'seed') ?? 1;

  return underLock(deps, async () => {
    if (hasFlag(argv, 'check')) {
      const { stale } = checkTasks(dbs.learning, dbs.index);
      deps.stderr(`episodic-memory learn: ${stale.length} stale task(s) marked\n`);
      return 0;
    }

    const runId = createRun(dbs.learning, {
      phase: 'improve',
      seed,
      budget: { maxCalls: config.maxCalls, maxUsd: config.maxUsd },
    });
    try {
      const result = await generateTasks(dbs.learning, dbs.index, {
        runId,
        seed,
        perProject: optionNumber(argv, 'per-project'),
        maxTasks: config.maxTasks,
        model: deps.generateModel,
      });
      deps.stderr(`episodic-memory learn: ${result.created} task(s) generated in run ${runId}\n`);
      finishRun(dbs.learning, runId, 'done', { created: result.created, byKindTier: result.byKindTier });
      return 0;
    } catch (error) {
      finishRun(dbs.learning, runId, 'failed', {});
      throw error;
    }
  });
}

async function commandSolve(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const config = learnConfig();
  const split = optionValue(argv, 'split') === 'test' ? 'test' : 'train';
  const explicitSnapshot = optionNumber(argv, 'snapshot');

  return underLock(deps, async pids => {
    const refusal = baselineRefusal(baselineCallCount(dbs.learning), config.maxCalls);
    if (refusal) {
      deps.stderr(`episodic-memory learn: ${refusal}\n`);
      return 1;
    }

    const tasks = listTasks(dbs.learning, { split });
    const limit = optionNumber(argv, 'limit');
    const toSolve = limit === undefined ? tasks : tasks.slice(0, limit);
    if (toSolve.length === 0) {
      deps.stderr(`episodic-memory learn: no ${split} tasks to solve; run learn tasks first\n`);
      return 0;
    }

    // The refuse-to-start gate stays the signal-train baseline (the measurement
    // a run must be able to afford). The batch itself may be larger — recall
    // and tier-1 rows are solved too — so a run can still spend past that
    // precheck. That overshoot is a stop, not a crash: see BudgetExhausted below.
    const runId = runIdForSolve(dbs.learning, toSolve, {
      maxCalls: config.maxCalls,
      maxUsd: config.maxUsd,
      split,
    });
    const snapshotId = explicitSnapshot ?? (await createSnapshot(dbs.learning, runId, undefined, dbs.store));

    deps.stderr(
      `episodic-memory learn: solving ${toSolve.length} ${split} task(s) in run ${runId} ` +
        `(snapshot ${snapshotId})\n`
    );

    try {
      const attempts = await solveMany(dbs, toSolve, {
        snapshotId,
        runId,
        role: 'solve',
        model: deps.model ?? config.model,
        pids,
        runAgent: deps.runAgent,
        judge: deps.judge,
        budget: new CallBudget(config.maxCalls),
      });

      const passed = attempts.filter(attempt => attempt.passed).length;
      const graded = attempts.filter(attempt => attempt.outcome === 'graded').length;
      deps.stderr(
        `episodic-memory learn: solved ${attempts.length} task(s), ${graded} graded, ${passed} passed\n`
      );
      finishRun(dbs.learning, runId, 'done', {
        solved: attempts.length,
        graded,
        passed,
        rate: passRate(dbs.learning, runId, snapshotId, { split, signalOnly: true }),
      });
      return 0;
    } catch (error) {
      if (error instanceof BudgetExhausted) {
        const kept = listAttempts(dbs.learning, { runId });
        finishRun(dbs.learning, runId, 'stopped', {
          solved: kept.length,
          budgetExhausted: true,
          maxCalls: error.max,
        });
        deps.stderr(
          `episodic-memory learn: call budget exhausted after ${error.max} subprocess calls; ` +
            `stopped run ${runId} and kept ${kept.length} validated attempt(s)\n`
        );
        return 0;
      }
      finishRun(dbs.learning, runId, 'failed', {});
      throw error;
    }
  });
}

/**
 * Refresh the exported skill tree after a run that can change the active set.
 *
 * The tree is derived output.
 * So a failure here is a warning on stderr, never a failed run.
 * The store already holds what the run learned.
 */
async function exportAfterRun(dbs: LearnDbs, deps: LearnCliDeps): Promise<void> {
  try {
    const result = await exportSkills(dbs);
    for (const warning of result.warnings) deps.stderr(`episodic-memory learn: export: ${warning}\n`);
    if (result.written.length > 0 || result.removed.length > 0) {
      deps.stderr(
        `episodic-memory learn: exported ${result.written.length} skill file(s), ` +
          `removed ${result.removed.length}\n`
      );
    }
  } catch (error) {
    deps.stderr(
      `episodic-memory learn: export failed: ${error instanceof Error ? error.message : String(error)}\n`
    );
  }
}

/**
 * `learn bootstrap`: map the eligible projects, gate the proposals, measure them.
 *
 * The baseline precheck runs first with a `×2` multiplier. Bootstrapping solves the
 * signal train set twice: once with an empty snapshot, then with the candidates.
 * A run that cannot afford that measurement spends the bootstrapper's cost and gets no
 * verdict. The precheck exists to prevent exactly that outcome.
 */
async function commandBootstrap(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const config = learnConfig();
  const seed = optionNumber(argv, 'seed') ?? 1;

  return underLock(deps, async pids => {
    const refusal = baselineRefusal(baselineCallCount(dbs.learning, 2), config.maxCalls);
    if (refusal) {
      deps.stderr(`episodic-memory learn: ${refusal}\n`);
      return 1;
    }

    deps.stderr(
      `episodic-memory learn: bootstrapping with concurrency ${config.concurrency}\n`
    );

    const { runBootstrap } = await import('./bootstrap.js');
    const budget = new CallBudget(config.maxCalls);
    let result: Awaited<ReturnType<typeof runBootstrap>>;
    try {
      result = await runBootstrap(dbs, {
        runAgent: deps.runAgent,
        model: deps.model ?? config.model,
        judge: deps.judge,
        concurrency: config.concurrency,
        perProject: optionNumber(argv, 'per-project'),
        seed,
        budget,
        pids,
        textModel: deps.generateModel,
      });
    } catch (error) {
      if (error instanceof BudgetExhausted) {
        deps.stderr(
          `episodic-memory learn: call budget exhausted after ${error.max} subprocess calls\n`
        );
        return 0;
      }
      throw error;
    }

    deps.stderr(
      `episodic-memory learn: bootstrap ${result.status}: ${result.projects} project(s), ` +
        `${result.proposed} proposed, ${result.activated.length} activated, ` +
        `${result.pending.length} pending, ${result.rejected.length} rejected ` +
        `(${result.runId})\n`
    );
    await exportAfterRun(dbs, deps);
    deps.stdout(formatReport(await buildReport(dbs, result.runId), false));
    return 0;
  });
}

/**
 * `learn improve`: the recursive learner over the signal train set.
 *
 * The baseline precheck runs first.
 * The run solves the whole signal set before it can decide anything.
 * A run that cannot afford that measurement would spend a solver batch and still have no verdict.
 * See spec §7 rule 10a.
 * A spend cap hit during the run is a stop, not a crash.
 * The run is marked `stopped` and keeps everything it validated, and the held-out split is still evaluated.
 */
async function commandImprove(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const config = learnConfig();
  const project = optionValue(argv, 'project') || undefined;
  const dryRun = hasFlag(argv, 'dry-run');
  const rounds = optionNumber(argv, 'rounds') ?? config.rounds;

  return underLock(deps, async pids => {
    const baseline = listTasks(dbs.learning, {
      split: 'train',
      kinds: SIGNAL_KINDS,
      tiers: SIGNAL_TIERS,
      ...(project === undefined ? {} : { project }),
    }).length;
    const refusal = baselineRefusal(baseline, config.maxCalls);
    if (refusal) {
      deps.stderr(`episodic-memory learn: ${refusal}\n`);
      return 1;
    }

    deps.stderr(
      `episodic-memory learn: improving with ${rounds} round(s), concurrency ${config.concurrency}` +
        `${dryRun ? ', dry run (no learners)' : ''}\n`
    );

    const budget = new CallBudget(config.maxCalls);
    let result: Awaited<ReturnType<typeof runLearn>>;
    try {
      result = await runLearn(dbs, {
        runAgent: deps.runAgent,
        model: deps.model ?? config.model,
        judge: deps.judge,
        textModel: deps.generateModel,
        concurrency: config.concurrency,
        rounds,
        leafMax: config.leafMax,
        ...(project === undefined ? {} : { project }),
        ...(dryRun ? { dryRun: true } : {}),
        budget,
        pids,
      });
    } catch (error) {
      if (error instanceof BudgetExhausted) {
        deps.stderr(
          `episodic-memory learn: call budget exhausted after ${error.max} subprocess calls; stopped\n`
        );
        return 0;
      }
      throw error;
    }

    deps.stderr(
      `episodic-memory learn: improve ${result.status}: ${result.children.length} child run(s), ` +
        `${result.kept.length} kept, ${result.merges.length} merge(s), ` +
        `${result.rejected.length} rejected (${result.runId})\n`
    );
    await exportAfterRun(dbs, deps);
    deps.stdout(formatReport(await buildReport(dbs, result.runId), false));
    return 0;
  });
}

function compareForStatus(
  a: { project: string; slug: string },
  b: { project: string; slug: string }
): number {
  const aGlobal = a.project === '*' ? 1 : 0;
  const bGlobal = b.project === '*' ? 1 : 0;
  if (aGlobal !== bGlobal) return aGlobal - bGlobal;
  if (a.project !== b.project) return a.project < b.project ? -1 : 1;
  return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
}

async function commandStatus(dbs: LearnDbs, deps: LearnCliDeps): Promise<number> {
  const entries = await dbs.store.listByStatus(['candidate', 'active', 'retired']);
  const lines: string[] = [`EPISODIC_MEMORY_LEARN=${learnEnabled() ? 'on' : 'off'}`];

  const counts = new Map<string, number>();
  for (const entry of entries) {
    const key = `${entry.kind}:${entry.status}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }

  lines.push('');
  lines.push(`entries (${entries.length}):`);
  if (entries.length === 0) lines.push('  none');
  for (const key of [...counts.keys()].sort()) lines.push(`  ${key}: ${counts.get(key)}`);

  const candidates = entries.filter(entry => entry.status === 'candidate').sort(compareForStatus);
  lines.push('');
  lines.push(`candidates awaiting approval (${candidates.length}):`);
  for (const entry of candidates) {
    lines.push(`  ${entry.kind} ${entry.project}/${entry.slug} v${entry.version}`);
  }
  if (candidates.length === 0) lines.push('  none');

  const run = latestRun(dbs.learning);
  lines.push('');
  if (!run) {
    lines.push('latest run: none');
  } else {
    lines.push(`latest run: ${run.id}`);
    lines.push(`  phase ${run.phase} · status ${run.status}${run.project ? ` · project ${run.project}` : ''}`);
    lines.push(`  metrics ${JSON.stringify(run.metrics)}`);
  }

  deps.stdout(lines.join('\n') + '\n');
  return 0;
}

/**
 * Resolve `learn approve`'s argument.
 *
 * Two forms are accepted.
 * The first is the entity name (`learned:<kind>:<project>:<slug>:v<n>`, what `learn status` and `learn report` print).
 * The second is the short `kind/project/slug`, which resolves to the latest version through `getBySlug`.
 * A project key can hold `-` and `.`, but never `/`.
 * So the short form splits on the first two slashes only.
 */
async function resolveEntry(
  dbs: LearnDbs,
  name: string
): Promise<{ entry: KnowledgeEntry } | { error: string }> {
  if (name.startsWith('learned:')) {
    const entry = await getEntry(dbs.store, name);
    return entry ? { entry } : { error: `no such entry: ${name}` };
  }

  const parts = name.split('/');
  if (parts.length < 3) {
    return { error: `not an entry name: ${name} (use learned:<kind>:<project>:<slug>:v<n> or kind/project/slug)` };
  }
  const [kind, project, ...rest] = parts;
  const slug = rest.join('/');
  if (kind !== 'instruction' && kind !== 'skill' && kind !== 'reflection') {
    return { error: `not a knowledge kind: ${kind}` };
  }
  if (!isValidSlug(slug)) return { error: `not a valid slug: ${slug}` };

  const entry = await getBySlug(dbs.store, kind as KnowledgeKind, project, slug);
  return entry ? { entry } : { error: `no such entry: ${name}` };
}

/** Split into lines, keeping a trailing empty line out of the diff. */
function splitLines(text: string): string[] {
  const lines = text.split('\n');
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return lines;
}

/**
 * A unified diff of two texts, `---`/`+++` headers and one hunk.
 *
 * The function is deliberately small.
 * The two sides are one entry body, so a full-file hunk is what a reviewer wants to read anyway.
 * An LCS over a handful of lines is enough to mark the changed ones.
 */
export function unifiedDiff(before: string, after: string, label: string): string {
  const a = splitLines(before);
  const b = splitLines(after);
  const lcs: number[][] = Array.from({ length: a.length + 1 }, () =>
    new Array<number>(b.length + 1).fill(0)
  );
  for (let i = a.length - 1; i >= 0; i -= 1) {
    for (let j = b.length - 1; j >= 0; j -= 1) {
      lcs[i][j] = a[i] === b[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }

  const body: string[] = [];
  let i = 0;
  let j = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) {
      body.push(` ${a[i]}`);
      i += 1;
      j += 1;
    } else if (lcs[i + 1][j] >= lcs[i][j + 1]) {
      body.push(`-${a[i]}`);
      i += 1;
    } else {
      body.push(`+${b[j]}`);
      j += 1;
    }
  }
  while (i < a.length) body.push(`-${a[i++]}`);
  while (j < b.length) body.push(`+${b[j++]}`);

  return [`--- ${label}`, `+++ ${label} (approved)`, ...body].join('\n');
}

/** The version this entry revises, or null for a first version. */
async function supersededVersion(
  dbs: LearnDbs,
  entry: KnowledgeEntry
): Promise<KnowledgeEntry | null> {
  if (entry.version > 1) {
    const previous = await getEntry(dbs.store, entryName(entry.kind, entry.project, entry.slug, entry.version - 1));
    if (previous) return previous;
  }
  const active = await dbs.store.listByStatus(['active'], [entry.kind]);
  return (
    active
      .filter(candidate => candidate.slug === entry.slug && candidate.project === entry.project)
      .filter(candidate => candidate.id !== entry.id && candidate.supersededBy === null)
      .sort((left, right) => right.version - left.version)[0] ?? null
  );
}

/** Ask `y` on a TTY. Anything else — including a bare newline — declines. */
async function confirmOnTty(question: string): Promise<boolean> {
  const { createInterface } = await import('node:readline/promises');
  const rl = createInterface({ input: process.stdin, output: process.stderr });
  try {
    const answer = await rl.question(question);
    return answer.trim().toLowerCase() === 'y';
  } finally {
    rl.close();
  }
}

/**
 * `learn approve <name>`: the human half of spec §7 rule 7.
 *
 * Instructions stay `candidate` under the default approval mode, precisely because every session loads them.
 * So this command is the review.
 * The command refuses an entry with no measurement or with a recorded regression.
 * Then the command prints the entry, that measurement and a unified diff.
 * The diff runs against the version that the entry revises.
 * With no earlier version, the diff runs against an empty body.
 * All of that output appears *before* the command activates anything.
 */
async function commandApprove(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const name = argv.find(arg => !arg.startsWith('-'));
  if (!name) {
    deps.stderr('episodic-memory learn: approve needs an entry name (kind/project/slug or learned:...)\n');
    return 2;
  }

  const resolved = await resolveEntry(dbs, name);
  if ('error' in resolved) {
    deps.stderr(`episodic-memory learn: ${resolved.error}\n`);
    return 1;
  }
  const { entry } = resolved;

  if (entry.status === 'active') {
    deps.stderr(`episodic-memory learn: ${entry.id} is already active\n`);
    return 0;
  }
  // A clean validation record is why it was active once. Retirement is a
  // later decision; approve must not undo it. Insert a new version instead.
  if (entry.status === 'retired') {
    deps.stderr(
      `episodic-memory learn: ${entry.id} is retired; refusing to re-activate it ` +
        '(approve a new version instead)\n'
    );
    return 1;
  }
  if (!entry.validation) {
    deps.stderr(
      `episodic-memory learn: ${entry.id} has no validation record; a candidate is approved ` +
        'only after a run measured it\n'
    );
    return 1;
  }
  if (entry.validation.regressions.length > 0) {
    deps.stderr(
      `episodic-memory learn: ${entry.id} regressed task(s) ${entry.validation.regressions.join(', ')}; ` +
        'refusing to approve\n'
    );
    return 1;
  }

  const previous = await supersededVersion(dbs, entry);
  const lines: string[] = [];
  lines.push(`${entry.id}`);
  lines.push(`kind ${entry.kind} · project ${entry.project} · slug ${entry.slug} · v${entry.version}`);
  lines.push(`status ${entry.status} · trust ${entry.trust} · confidence ${entry.confidence}`);
  lines.push(`scope ${entry.scope}`);
  lines.push(`description ${entry.description}`);
  lines.push('');
  lines.push('validation:');
  lines.push(JSON.stringify(entry.validation, null, 2));
  lines.push('');
  lines.push(previous ? `diff against ${previous.id}:` : 'diff against (no earlier version):');
  lines.push(
    unifiedDiff(
      previous?.body ?? '',
      entry.body,
      previous ? `${previous.id} body` : 'empty body'
    )
  );
  lines.push('');
  deps.stdout(lines.join('\n') + '\n');

  if (!hasFlag(argv, 'yes')) {
    if (!process.stdin.isTTY) {
      deps.stderr(
        'episodic-memory learn: not a TTY; pass --yes to approve without an interactive prompt\n'
      );
      return 1;
    }
    const ok = await confirmOnTty(`Approve ${entry.id} as ground truth? [y/N] `);
    if (!ok) {
      deps.stderr(`episodic-memory learn: ${entry.id} left as ${entry.status}\n`);
      return 1;
    }
  }

  await activate(dbs.store, entry.id, entry.validation, 'ground-truth');
  await writeLearnedBlocks(dbs.store, dbs.learning, learnConfig().maxChars);
  await exportAfterRun(dbs, deps);

  deps.stderr(`episodic-memory learn: approved ${entry.id} (trust ground-truth)\n`);
  return 0;
}

/**
 * `learn export [--to DIR]`: write the active skills out.
 *
 * The export replaces the default root wholesale, because the root is generated output.
 * `--to` copies the active skills into DIR, such as a project's own directory.
 * The copy removes nothing there, because the plugin must never delete a file it did not write (spec §5.4).
 */
async function commandExport(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const to = optionValue(argv, 'to');
  const result = await exportSkills(dbs, to ? to : undefined, to ? { prune: false } : undefined);

  for (const warning of result.warnings) deps.stderr(`episodic-memory learn: export: ${warning}\n`);
  const where = to ?? path.join(getSuperpowersDir(), 'learned-skills');
  deps.stdout(
    `exported ${result.written.length} skill(s) to ${where}` +
      (result.removed.length > 0 ? `, removed ${result.removed.length} stale director${result.removed.length === 1 ? 'y' : 'ies'}` : '') +
      '\n'
  );
  return result.written.length > 0 || result.warnings.length === 0 ? 0 : 1;
}

/**
 * `learn render [--project P]`: rewrite the learned-hints blocks from the active entries.
 *
 * The command then prints what it wrote.
 * With `--project P`, the command prints that project's block text, or fails when the project has none.
 * Without `--project`, the command prints the block count and each block's length in characters.
 *
 * A learner round that keeps an entry, a bootstrap run that completes and `learn approve` write the blocks too.
 * The command exists for a store that a person edits by hand.
 * Use `--project` to see the text that a new session receives.
 */
async function commandRender(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  await writeLearnedBlocks(dbs.store, dbs.learning, learnConfig().maxChars);
  const rows = dbs.learning
    .prepare('SELECT project, text FROM learned_block ORDER BY project')
    .all() as Array<{ project: string; text: string }>;

  const project = optionValue(argv, 'project');
  if (project) {
    const row = rows.find(r => r.project === project);
    if (!row) {
      deps.stderr(`episodic-memory learn: no learned-hints block for project '${project}'\n`);
      return 1;
    }
    deps.stdout(row.text.endsWith('\n') ? row.text : `${row.text}\n`);
    return 0;
  }

  deps.stdout(`rendered ${rows.length} learned-hints block(s)\n`);
  for (const row of rows) deps.stdout(`  ${row.project}: ${row.text.length} chars\n`);
  return 0;
}

async function commandReport(dbs: LearnDbs, argv: string[], deps: LearnCliDeps): Promise<number> {
  const runId = optionValue(argv, 'run') || latestRunId(dbs.learning);
  if (!runId) {
    deps.stderr('episodic-memory learn: no learning run recorded yet; run learn tasks or learn solve first\n');
    return 1;
  }
  if (!getRun(dbs.learning, runId)) {
    deps.stderr(`episodic-memory learn: no such run: ${runId}\n`);
    return 1;
  }
  deps.stdout(formatReport(await buildReport(dbs, runId), hasFlag(argv, 'json')));
  return 0;
}

/**
 * Parse and run one `learn` subcommand.
 *
 * The returned number is the process exit code. `deps.dbs` is a test seam: a
 * real invocation opens and always closes its own handles.
 */
export async function runLearnCli(argv: string[], deps: LearnCliDeps): Promise<number> {
  const command = argv[0];

  if (command === undefined || command === '--help' || command === '-h') {
    deps.stdout(LEARN_USAGE + '\n');
    return 0;
  }

  // Flag off wins over everything: spec §7 rule 1 says every `learn` subcommand
  // exits 0 with this message.
  if (!learnEnabled()) {
    deps.stderr(`${LEARN_OFF_MESSAGE}\n`);
    return 0;
  }

  if (!IMPLEMENTED.has(command)) {
    deps.stderr(`episodic-memory learn: unknown command '${command}'\n\n${LEARN_USAGE}\n`);
    return 2;
  }

  let owned: LearnDbs | null = null;
  try {
    const dbs = deps.dbs ?? (owned = await openDbs());
    switch (command) {
      case 'tasks':
        return await commandTasks(dbs, argv.slice(1), deps);
      case 'solve':
        return await commandSolve(dbs, argv.slice(1), deps);
      case 'bootstrap':
        return await commandBootstrap(dbs, argv.slice(1), deps);
      case 'improve':
        return await commandImprove(dbs, argv.slice(1), deps);
      case 'status':
        return await commandStatus(dbs, deps);
      case 'approve':
        return await commandApprove(dbs, argv.slice(1), deps);
      case 'export':
        return await commandExport(dbs, argv.slice(1), deps);
      case 'render':
        return await commandRender(dbs, argv.slice(1), deps);
      default:
        return await commandReport(dbs, argv.slice(1), deps);
    }
  } finally {
    if (owned) closeDbs(owned);
  }
}
